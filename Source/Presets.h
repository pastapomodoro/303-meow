// ─────────────────────────────────────────────────────────────────────────────
// Full preset: synth params + FX + pattern
// ─────────────────────────────────────────────────────────────────────────────
struct PresetData
{
    const char* name;
    float cutoff, resonance, envMod, decay;
    float accent, volume, distortion, tuning;
    float tempo;
    int   waveform;
    float subOsc;                     // 0..1, ottava sotto
    float delayTime, delayFeedback, delayMix;
    float reverbSize, reverbMix;
    int   patternLength;
    struct StepData {
        int  note; bool gate, accent, slide; int octave;
    };
    // 8 variazioni della stessa linea, una per tasto Pattern. Caricare un
    // banco riempie tutti gli slot del sequencer, cosi' i tasti 1..8 sono
    // variazioni della stessa idea e non pattern slegati: si passa da uno
    // all'altro mentre suona e il pezzo si costruisce.
    StepData variations[8][16];
};

// ─────────────────────────────────────────────────────────────────────────────
// Synth-only preset: no pattern data
// ─────────────────────────────────────────────────────────────────────────────
struct SynthPresetData
{
    const char* name;
    float cutoff, resonance, envMod, decay;
    float accent, volume, distortion, tuning;
    int   waveform;
    float subOsc;
    float delayTime, delayFeedback, delayMix;
    float reverbSize, reverbMix;
};

